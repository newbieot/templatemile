"""Build the exact postcode/zone lookup from the operator's reference workbook."""
import argparse
import hashlib
import json
import re
from pathlib import Path

from openpyxl import load_workbook


def build(source, target):
    workbook = load_workbook(source, read_only=True, data_only=True)
    sheet = workbook['Sheet1']
    rows = sheet.iter_rows(values_only=True)
    if tuple(next(rows)) != ('Kode Pos', 'Kantor', 'Kode Pos Zona', 'Kantor'):
        raise ValueError('Unexpected mapping columns; inspect the source before rebuilding.')

    def identifier(value):
        if isinstance(value, (int, float)) and float(value).is_integer():
            return str(int(value))
        return str(value or '').strip()

    mapping = {}
    source_count = 0
    for row_number, (postcode, _, zone, _) in enumerate(rows, start=2):
        postcode, zone = identifier(postcode), identifier(zone)
        if not re.fullmatch(r'\d{5}', postcode) or not re.fullmatch(r'\d{5}(?:[A-Z]\d+)?', zone):
            raise ValueError(f'Invalid postcode/zone at source row {row_number}')
        if postcode in mapping:
            raise ValueError(f'Duplicate postcode at source row {row_number}: {postcode}')
        mapping[postcode] = zone
        source_count += 1
    workbook.close()

    overrides = json.loads(Path(__file__).with_name('postcode-zone-overrides.json').read_text(encoding='utf-8'))
    for postcode, override in overrides.items():
        if postcode in mapping and mapping[postcode] != override['zone']:
            raise ValueError(f'Override conflicts with reference: {postcode}')
        mapping[postcode] = override['zone']

    metadata = {
        'file': source.name, 'sheet': 'Sheet1',
        'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'sourceRecordCount': source_count, 'recordCount': len(mapping), 'overrides': overrides,
    }
    groups = {}
    for postcode, zone in sorted(mapping.items()):
        groups.setdefault(zone, []).append(postcode)
    lines = [f'    {json.dumps(zone)}: {json.dumps(postcodes, separators=(",", ":"))}'
             for zone, postcodes in sorted(groups.items())]
    javascript = '''// Generated by scripts/build-postcode-zones.py. Preserve exact source identifiers.
(function (root) {
  'use strict';
  const source = Object.freeze(SOURCE_METADATA);
  const groups = {
ZONE_GROUPS
  };
  const zones = Object.freeze(Object.fromEntries(Object.entries(groups)
    .flatMap(([zone, postcodes]) => postcodes.map(postcode => [postcode, zone]))));

  function resolve(postcode) {
    const value = String(postcode ?? '').trim();
    if (!/^\\d{5}$/.test(value)) throw new Error(`Kode pos ${value || '(kosong)'} harus terdiri dari 5 digit.`);
    if (!Object.prototype.hasOwnProperty.call(zones, value)) {
      // Operator policy: unknown 294xx codes route through Batam 29400.
      // Exact reference entries (including Galang 29664) always win.
      if (/^294\\d{2}$/.test(value)) return '29400';
      throw new Error(`Kode pos ${value} belum ada dalam referensi kode pos zona. Lengkapi referensi sebelum ekspor.`);
    }
    return zones[value];
  }

  function isBelakangPadang(region = {}, address = '') {
    return String(region.district || '').toUpperCase().replace(/[^A-Z]/g, '') === 'BELAKANGPADANG'
      || /^2949[1-6]$/.test(String(region.postcode || ''))
      || /\\bBELAKANG[\\s.-]*PADANG\\b/i.test(address);
  }

  function isLocalBatam(region = {}) {
    return /^(?:KOTA\\s+)?BATAM$/i.test(String(region.city || '').trim()) && !isBelakangPadang(region);
  }

  const api = Object.freeze({ resolve, isLocalBatam, isBelakangPadang, source, zones });
  root.MilePostalZones = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
'''.replace('SOURCE_METADATA', json.dumps(metadata, ensure_ascii=False, separators=(',', ':'))).replace('ZONE_GROUPS', ',\n'.join(lines))
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(javascript, encoding='utf-8', newline='\n')
    print(json.dumps({'sourceRecords': source_count, 'records': len(mapping), 'bytes': target.stat().st_size}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('source', type=Path)
    parser.add_argument('target', type=Path)
    args = parser.parse_args()
    build(args.source, args.target)
